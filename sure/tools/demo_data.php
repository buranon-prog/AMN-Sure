/**
 * ใส่ข้อมูลตัวอย่างผ่าน rec_save() (ผ่าน validation เดียวกับหน้าเว็บ) ในนามผู้ใช้ Manager ที่ระบุ
 * ลำดับ: ลูกค้า → สาขา → เครื่อง → ติดตามลูกค้า → การขาย → รับชำระเงิน → บริการ → ต้นทุนเครื่อง
 */
function demo_seed(string $managerUserId): void
{
    act_as($managerUserId);
    $samples = demo_samples();
    tx(function () use ($samples) {
        foreach (['C', 'B', 'D', 'A', 'S', 'P', 'V', 'T'] as $t) {
            foreach ($samples[$t] as $row) {
                $input = [];
                foreach ($row as $k => $v) $input[$k] = is_int($v) || is_float($v) ? (string) $v : $v;
                rec_save($t, null, $input);
            }
        }
    });
}
